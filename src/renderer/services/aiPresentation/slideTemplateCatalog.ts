/**
 * Returns all registered slide template definitions.
 */
export function getAllSlideTemplates(): SlideTemplateDefinition[] {
  return MASTER_SLIDE_TEMPLATES;
}

/**
 * Finds a slide template by ID with safe fallback to `concept-explanation`.
 */
export function getSlideTemplateById(id: string): SlideTemplateDefinition {
  const match = MASTER_SLIDE_TEMPLATES.find((t) => t.id === id);
  if (match) return match;

  // Handle aliases
  if (id === 'concept-overview') return TEMPLATE_CONCEPT_EXPLANATION;
  if (id === 'definition-formula') return TEMPLATE_MATHEMATICAL_DERIVATION;
  if (id === 'timeline-milestones') return TEMPLATE_STEP_PROCESS;
  if (id === 'summary-quiz') return TEMPLATE_SUMMARY_TAKEAWAY;
  if (id === 'three-card-grid' || id === 'four-card-grid') return TEMPLATE_STEP_PROCESS;

  return TEMPLATE_CONCEPT_EXPLANATION;
}

/**
 * Resolves a template based on layout archetype.
 */
export function matchTemplateByLayout(layout: SlideLayoutType | string): SlideTemplateDefinition {
  return getSlideTemplateById(layout);
}

